import { test, expect } from '@playwright/test'
import { installCoreFixture, seedToken } from './core-fixture'

test('真实页面完成创建、两轮发送、刷新恢复与设置返回', async ({ page }) => {
  await installCoreFixture(page)
  await seedToken(page)
  await page.goto('/')
  await page.getByRole('button', { name: '新建会话', exact: true }).first().click()
  await expect(page).toHaveURL(/\/sessions\/s2$/)
  await expect(page.getByRole('textbox', { name: '消息' })).toBeEnabled()
  await page.getByRole('textbox', { name: '消息' }).fill('第一轮')
  await page.getByRole('button', { name: '发送消息' }).click()
  await expect(page.getByText('已收到：第一轮', { exact: true })).toBeVisible()
  await page.getByRole('textbox', { name: '消息' }).fill('第二轮')
  await page.getByRole('button', { name: '发送消息' }).click()
  await expect(page.getByText('已收到：第二轮', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('已收到：第一轮', { exact: true })).toBeVisible()
  await expect(page.getByText('已收到：第二轮', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: '设置' }).click()
  await expect(page.getByText('尚未注册工具。你仍然可以使用服务提供的对话能力。')).toBeVisible()
  await page.getByRole('button', { name: '深色', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByRole('link', { name: '返回会话' }).click()
  await expect(page.getByText('已收到：第二轮', { exact: true })).toBeVisible()
})
test('中文输入法 Enter 不误发送，窄屏无横向溢出', async ({ page }) => {
  await installCoreFixture(page)
  await seedToken(page)
  await page.setViewportSize({ width: 320, height: 740 })
  await page.goto('/sessions/s1')
  const input = page.getByRole('textbox', { name: '消息' })
  await input.fill('中文输入')
  await input.dispatchEvent('keydown', { key: 'Enter', isComposing: true })
  await expect(input).toHaveValue('中文输入')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('外部工具等待、停止确认和窄屏详情可操作', async ({ page }) => {
  await installCoreFixture(page, 'waiting')
  await seedToken(page)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/sessions/s1')
  await page.getByRole('textbox', { name: '消息' }).fill('等待外部工具')
  await page.getByRole('button', { name: '发送消息' }).click()
  await expect(page.getByRole('status')).toContainText('等待外部工具结果')
  await page.getByRole('button', { name: '执行详情', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByText('external-tool', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByRole('button', { name: '停止运行' }).click()
  await expect(page.getByRole('status')).toContainText('等待停止确认')
  await expect(page.getByRole('button', { name: '发送消息' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('运行失败显示实际错误，无模型配置入口', async ({ page }) => {
  await installCoreFixture(page, 'failed')
  await seedToken(page)
  await page.goto('/sessions/s1')
  await page.getByRole('textbox', { name: '消息' }).fill('失败场景')
  await page.getByRole('button', { name: '发送消息' }).click()
  await page.getByRole('button', { name: '执行详情', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('模型请求失败')
  await expect(page.getByRole('button', { name: '批准', exact: true })).toHaveCount(0)
})
